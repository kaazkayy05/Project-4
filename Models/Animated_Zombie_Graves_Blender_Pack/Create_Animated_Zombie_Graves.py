"""
ZOMBIE HANDS EMERGING FROM GRAVES — BLENDER 4.x / 5.x

Usage:
  1) Extract the ZIP into a folder, keeping geometry.py beside this script.
  2) Open Blender > Scripting > Text Editor > Open this .py file > Run Script.
  3) Press NUMPAD 0 for the camera view; SPACE to play animation (frames 1–180).
  4) Render a still at frame 154 (F12) or render the animation (Ctrl-F12).
  5) File > Save As > Zombie_Graves_Animated.blend.

Five different rising hands, four uniquely shaped tombstones.
All visible meshes are generated by the geometry.py module bundled with this script;
the PNG reference preview uses those same mesh vertices and triangles.
"""
import bpy
import math
import os
import sys
import random
from mathutils import Vector

BASE=os.path.dirname(os.path.abspath(__file__)) if '__file__' in globals() else bpy.path.abspath('//')
if BASE not in sys.path:sys.path.insert(0, BASE)
import geometry as geo

# CLEAN SCENE
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)
for collection in list(bpy.data.collections):
    if collection.users == 0:
        bpy.data.collections.remove(collection)

scene=bpy.context.scene
scene.frame_start=1
scene.frame_end=180
scene.render.fps=30
scene.render.resolution_x=1600
scene.render.resolution_y=900
scene.render.resolution_percentage=100
scene.render.engine='CYCLES'
scene.cycles.samples=64
scene.render.image_settings.file_format='PNG'
scene.render.filepath=os.path.join(BASE,'Zombie_Graves_Render.png')

try:
    scene.view_settings.view_transform='AgX'
except Exception:pass

# Collections
collections={}
def get_collection(name):
    if name not in collections:
        col=bpy.data.collections.new(name)
        scene.collection.children.link(col)
        collections[name]=col
    return collections[name]

mats={}
def mat(name, rgb, roughness=.88, metallic=0):
    if name not in mats:
        m=bpy.data.materials.new(name)
        m.diffuse_color=(*rgb,1)
        m.use_nodes=True
        bsdf=m.node_tree.nodes.get('Principled BSDF')
        bsdf.inputs['Base Color'].default_value=(*rgb,1)
        bsdf.inputs['Roughness'].default_value=roughness
        bsdf.inputs['Metallic'].default_value=metallic
        # Subtle roughness and bump for aged stone and skin; no external textures.
        if any(s in name for s in ['stone','skin','fabric','ground','dirt']):
            nodes=m.node_tree.nodes; links=m.node_tree.links
            noise=nodes.new('ShaderNodeTexNoise')
            noise.inputs['Scale'].default_value=9 if 'stone' in name else 14
            noise.inputs['Detail'].default_value=3
            noise.inputs['Roughness'].default_value=.7
            bump=nodes.new('ShaderNodeBump')
            bump.inputs['Strength'].default_value=.17 if 'stone' in name else .075
            bump.inputs['Distance'].default_value=.038 if 'stone' in name else .012
            links.new(noise.outputs['Fac'],bump.inputs['Height'])
            links.new(bump.outputs['Normal'],bsdf.inputs['Normal'])
        mats[name]=m
    return mats[name]

for colorname,rgb in geo.COLORS.items():
    mat(colorname,rgb)

geo.create_all()
roots={}
for index,pos in enumerate(geo.HAND_ROOTS):
    group=f'Hand_{index+1:02d}'
    empty=bpy.data.objects.new(f'{group}_ANIMATED_RISE_ROOT',None)
    get_collection(f'Animated_{group}').objects.link(empty)
    empty.empty_display_type='ARROWS'
    empty.empty_display_size=.3
    roots[group]=empty

for part in geo.PARTS:
    me=bpy.data.meshes.new(part.name+'_Mesh')
    me.from_pydata(part.vertices,[],part.faces)
    me.update()
    ob=bpy.data.objects.new(part.name,me)
    colname='Graveyard_Static' if part.collection=='Static' else 'Animated_'+part.collection
    get_collection(colname).objects.link(ob)
    # The geometry is directly shared with the VTK preview.
    name=next((name for name, rgb in geo.COLORS.items() if rgb==part.color),'stone')
    ob.data.materials.append(mats[name])
    if part.collection!='Static':
        ob.parent=roots[part.collection]
    for poly in ob.data.polygons:
        poly.use_smooth=part.name.split('_')[-1] not in ('Paving','Shaft')
    # An optional bevel only for sharp-sided tombstones (not for the hands).
    if part.collection=='Static' and (part.name.startswith(('01_','02_','03_','04_'))):
        if ('Stem' in part.name or 'Bar' in part.name or 'Plinth' in part.name or 'Base' in part.name or 'Foot' in part.name):
            mod=ob.modifiers.new('Small weathered stone edge','BEVEL')
            mod.width=.032;mod.segments=2
            if hasattr(mod, 'affect'):
                mod.affect='EDGES'
            mod.profile=.65
            wn=ob.modifiers.new('Weighted corners','WEIGHTED_NORMAL')

# Emersion keyframes; every arm starts below the actual 3D ground and rises out.
for i,(name,root) in enumerate(roots.items()):
    x,y,z=geo.HAND_ROOTS[i]
    lean, curl, spread=geo.HAND_POSES[i]
    start=7+i*8
    # Each staggered burst takes ~2.8 seconds, followed by small twitch / settling.
    keys=[(1,-2.95,-14),(start,-2.95,-14),
          (start+18,-1.95,8),(start+35,-.88,-5),
          (start+52,-.30,6),(start+72,0,-2),
          (start+94,.045,4),(180,.025,1)]
    for fr,zz,sway in keys:
        root.location=(x,y,zz)
        root.rotation_euler=(math.radians(-8+sway*.15),math.radians(lean+sway), math.radians(i*7-12))
        root.keyframe_insert(data_path='location',frame=fr)
        root.keyframe_insert(data_path='rotation_euler',frame=fr)
    if root.animation_data and root.animation_data.action:
        for curve in getattr(root.animation_data.action, 'fcurves', []):
            for key in curve.keyframe_points:
                key.interpolation='BEZIER'

# Soil debris bursts away as each hand breaks the ground.
rng=random.Random(2026)
for i,(x,y,_) in enumerate(geo.HAND_ROOTS):
    start=7+i*8
    for j in range(14):
        a=rng.uniform(0,math.tau);dist=rng.uniform(.14,.52)
        ob=bpy.data.objects.new(f'Hand_{i+1:02d}_Kicked_Up_Dirt_{j:02d}',None)
        # Use a real small irregular stone mesh rather than a Blender primitive object.
        verts=[(-.05,-.04,-.04),(.06,-.01,-.04),(.03,.07,-.02),(-.03,.04,.05),(.01,-.03,.07)]
        faces=[(0,1,2),(0,2,3),(0,3,4),(0,4,1),(1,4,3,2)]
        me=bpy.data.meshes.new(ob.name+'_Mesh');me.from_pydata(verts,[],faces);me.update();ob.data=me
        get_collection('Animated_Soil_Bursts').objects.link(ob)
        ob.data.materials.append(mats['loam' if j%2 else 'dirt'])
        ob.scale=(.1,.1,.1)
        ob.location=(x+dist*math.cos(a),y+dist*math.sin(a),.05)
        for fr,point,sc in [
            (1,(x+dist*math.cos(a),y+dist*math.sin(a),-.1),0.001),
            (start+18,(x+dist*math.cos(a),y+dist*math.sin(a),-.1),0.001),
            (start+24,(x+dist*math.cos(a),y+dist*math.sin(a),.08),1),
            (start+43,(x+(dist+.20)*math.cos(a),y+(dist+.20)*math.sin(a),rng.uniform(.4,1.0)),1),
            (start+68,(x+(dist+.65)*math.cos(a),y+(dist+.65)*math.sin(a),.04),.8),
            (start+90,(x+(dist+.65)*math.cos(a),y+(dist+.65)*math.sin(a),.04),.8)]:
            ob.location=point;ob.scale=tuple(sc*s for s in (rng.uniform(.7,1.6),)*3)
            ob.keyframe_insert('location',frame=fr)
            ob.keyframe_insert('scale',frame=fr)

# CAMERA: angled cinematic view with all 4 memorials fully visible.
def point_at(ob, target):
    direction=Vector(target)-ob.location
    ob.rotation_euler=direction.to_track_quat('-Z','Y').to_euler()

bpy.ops.object.camera_add(location=(8.2,-14.6,8.15))
cam=bpy.context.object
cam.name='Camera_4_Tombstones_and_Zombie_Hands'
point_at(cam,(0,.12,1.50))
cam.data.type='ORTHO'
cam.data.ortho_scale=16.8
scene.camera=cam

# Physical key, rim and moonlit atmosphere
world=bpy.data.worlds.new('Dusk_Graveyard_World') if not bpy.data.worlds else bpy.data.worlds[0]
scene.world=world
world.use_nodes=True
bg=world.node_tree.nodes.get('Background')
bg.inputs['Color'].default_value=(.075,.095,.112,1)
bg.inputs['Strength'].default_value=.48

def area(name, location, energy, color, size, target=(0,.2,1.2)):
    data=bpy.data.lights.new(name,'AREA')
    obj=bpy.data.objects.new(name,data)
    get_collection('Lighting').objects.link(obj)
    obj.location=location
    data.energy=energy
    data.shape='DISK';data.size=size
    data.color=color
    point_at(obj,target)

area('Cool_Moon_Key',(1,-3,10),1900,(.69,.79,1.0),8)
area('Warm_Graveyard_Fill',(-7,-5,5),1150,(1.0,.76,.52),9)
area('Moon_Rim_Behind',(0,5,9),2400,(.55,.75,1),7)

# Stage background, optional black gradient horizon (world already supplies it)
scene.frame_set(154)

# Save automatically beside the script when run with Blender GUI or background.
bpy.ops.wm.save_as_mainfile(filepath=os.path.join(BASE,'Zombie_Graves_Animated.blend'))
print('CREATED: five keyframed rising hands, four distinctive tombstones, 180 frames at 30fps.')
print('SAVED:',os.path.join(BASE,'Zombie_Graves_Animated.blend'))
print('RENDER: select frame 154 for the finished pose, press F12. Play for emerging animation.')
